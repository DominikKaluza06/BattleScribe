package com.example.battlescribe;

/**
 * Defines the available equipment slots for the player.
 * Used to categorize items and determine where they can be equipped.
 */
public enum SlotType {
    WEAPON,  // Primary damage source
    HELMET,  // Head protection
    BOOTS,   // Increases speed (Agility)
    RING,    // Accessory for various bonuses
    ARMOR    // Body protection (Vitality/Defense)
}
